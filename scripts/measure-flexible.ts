/**
 * Classifies flexible LDraw parts into the four kinds BrickMotion can reason
 * about (cloth, hose, string, rubber) and writes src/data/flexibleParts.ts.
 *
 *   npx tsx scripts/measure-flexible.ts
 *
 * The classification is data-only: it reads the part title and !CATEGORY from
 * public/ldraw/parts. It deliberately does not treat every title containing
 * "flex", "cable" or "rubber" as flexible: hoses have reels and air pumps,
 * rubber bands have holders, and cloth appears in printed patterns.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const PARTS = join(ROOT, 'public', 'ldraw', 'parts');
const OUT = join(ROOT, 'src', 'data', 'flexibleParts.ts');

type Kind = 'cloth' | 'hose' | 'string' | 'rubber';
type Row = { part: string; title: string; category: string; kind: Kind };

const canonical = (part: string) => part.toLowerCase().replace(/\.dat$/, '').split('/').pop() ?? '';

function header(file: string): { title: string; category: string } {
  let title = '';
  let category = '';
  const lines = readFileSync(join(PARTS, file), 'utf8').split('\n').slice(0, 40);
  for (const line of lines) {
    if (/^0\s+!CATEGORY\b/i.test(line)) category = line.replace(/^0\s+!CATEGORY\s*/i, '').trim();
    if (/^0\s+/.test(line) && !/^0\s+!/.test(line) && !title) title = line.slice(2).trim();
  }
  return { title, category };
}

function classify(title: string, category: string): Kind | null {
  const t = title.replace(/^[~_=]+\s*/, '').trim().toLowerCase();
  if (category === 'Hose') return 'hose';
  if (/^(hose flexible|technic ribbed hose|technic flex-system hose|cable flexible)\b/.test(t)) return 'hose';
  if (/^hose\s+\d/.test(t)) return 'hose';

  if (category === 'Sheet Fabric') return 'cloth';
  if (/^(sail|net|tent|cloth|fabric)\b/.test(t)) return 'cloth';

  if (/^(string|rope|thread|cord|ripcord)\b/.test(t)) return 'string';
  if (/^technic flex-system cable\b/.test(t)) return 'string';

  if (/^rubber (belt|band|ring)\b/.test(t)) return 'rubber';
  if (/^(technic axle flexible|technic axle joiner double flexible|bar flexible|claw flexible)\b/.test(t)) return 'rubber';
  return null;
}

const rows: Row[] = [];
for (const file of readdirSync(PARTS)) {
  if (!/\.dat$/i.test(file)) continue;
  const { title, category } = header(file);
  const kind = classify(title, category);
  if (kind) rows.push({ part: canonical(file), title, category, kind });
}
rows.sort((a, b) => a.part.localeCompare(b.part));

const counts = { cloth: 0, hose: 0, string: 0, rubber: 0 };
for (const row of rows) counts[row.kind]++;

const body = rows.map((r) => `  ${JSON.stringify(r.part)}: ${JSON.stringify(r.kind)},`).join('\n');
const date = new Date().toISOString().slice(0, 10);
const text = `// GENERATED by scripts/measure-flexible.ts on ${date}. Do not edit by hand.
// Flexible parts classified from their LDraw title and !CATEGORY.

export type FlexibleKind = 'cloth' | 'hose' | 'string' | 'rubber';

export const flexibleParts: Readonly<Record<string, FlexibleKind>> = {
${body}
};

const normalize = (part: string) => part.toLowerCase().replace(/\\.dat$/, '').split('/').pop() ?? '';

export function flexibleKind(part: string): FlexibleKind | null {
  return flexibleParts[normalize(part)] ?? null;
}
`;
writeFileSync(OUT, text);

console.log(`Classified ${rows.length} flexible parts in ${statSync(OUT).size} bytes → ${OUT}`);
console.log(`  cloth ${counts.cloth}, hose ${counts.hose}, string ${counts.string}, rubber ${counts.rubber}`);
for (const kind of ['cloth', 'hose', 'string', 'rubber'] as const) {
  const sample = rows.filter((r) => r.kind === kind).slice(0, 6).map((r) => `${r.part} ${r.title}`);
  console.log(`  ${kind}: ${sample.join(' | ')}`);
}
