#!/usr/bin/env tsx
/**
 * Reads BrickLink Studio's per-part connectivity (`ldraw/connectivity/<part>.conn`) into
 * `src/data/studioConnectors.generated.ts`, so the editor can use the connections Studio
 * authors by hand where neither the LDraw geometry nor the LDCad shadow pack has one.
 *
 * Only the codes verified against parts this project already measures are imported — the stud
 * (0x170003) and anti-stud (0x2, 0x10002) families. Studio's pins, axles, clips, ball joints and
 * outer-face markers carry codes whose shape is not verified here, so they are counted and left
 * out rather than guessed at. Every connection is also checked against the part's own measured
 * body box: a point more than `MARGIN` outside it is a record this importer has misread, and is
 * dropped instead of becoming a connector.
 *
 *   npx tsx scripts/import-studio-connectivity.ts [connectivity-dir]
 *
 * Studio's path differs by platform; the default is the macOS one, and the argument (or
 * STUDIO_CONNECTIVITY) overrides it. Needs the LDraw library at public/ldraw (npm run setup).
 */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PartLibrary } from '../src/ldraw/library';
import { measurePart } from '../src/ldraw/metrics';
import { partConnectors } from '../src/plan/connectors';
import { shadowLookupFrom } from '../src/ldraw/shadow';
import { parseStudioConnectivity, studioConnections, type StudioConnection } from '../src/data/studioConnectivity';

const DEFAULT_DIR = '/Applications/Studio 2.0/ldraw/connectivity';
const dir = process.argv[2] ?? process.env.STUDIO_CONNECTIVITY ?? DEFAULT_DIR;
const LDRAW = join('public', 'ldraw');
const OUT = join('src', 'data', 'studioConnectors.generated.ts');
/** How far outside a part's measured body a connection may sit and still be believed. */
const MARGIN = 10;

/** 1, 10, 20.5, -10 — short, and exact for the half-LDU values Studio writes. */
const num = (v: number) => String(Math.round(v * 100) / 100);
const key = (c: StudioConnection) => `${c.gender} ${c.pos.map(num).join(' ')} ${c.axis.map(num).join(' ')}`;

async function main(): Promise<void> {
  if (!existsSync(dir)) {
    console.error(`Studio connectivity not found at ${dir}\nPass the directory, or set STUDIO_CONNECTIVITY.`);
    process.exit(1);
  }
  if (!existsSync(join(LDRAW, 'parts'))) {
    console.error('No parts library at public/ldraw. Run `npm run setup` first.');
    process.exit(1);
  }
  const shadowPath = join('public', 'data', 'ldcad-shadow.json');
  const shadow = existsSync(shadowPath) ? shadowLookupFrom(JSON.parse(readFileSync(shadowPath, 'utf8')).files) : undefined;
  const lib = new PartLibrary(async (p) => {
    const f = join(LDRAW, p);
    return statSync(f, { throwIfNoEntry: false })?.isFile() ? readFileSync(f, 'utf8') : null;
  }, shadow);

  const files = readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.conn')).sort();
  const table: Record<string, string> = {};
  let parts = 0, kept = 0, outside = 0, left = 0, noModel = 0, unclear = 0, ambiguous = 0;
  for (const [i, file] of files.entries()) {
    const part = file.slice(0, -'.conn'.length).toLowerCase();
    const { records, complete } = parseStudioConnectivity(new Uint8Array(readFileSync(join(dir, file))));
    if (!complete) { unclear++; continue; }
    const usable = studioConnections(records);
    left += records.length - usable.length;
    if (!usable.length) continue;
    const flat = await lib.loadPart(`${part}.dat`);
    if (!flat) { noModel++; continue; }
    const measured = measurePart(flat, part);
    // Studio's codes do not separate a stud from a pin shaft (4274's outer end is recorded with
    // the stud code and is a pin), so a part that already has a shaft cannot be read safely from
    // these files: it keeps the connectors the geometry and the shadow pack give it.
    if (partConnectors(measured).some((c) => c.type !== 'stud')) { ambiguous++; continue; }
    const body = measured.body;
    const inside = (p: readonly number[]) => [0, 1, 2].every((k) => p[k] >= body.min[k] - MARGIN && p[k] <= body.max[k] + MARGIN);
    const own: string[] = [];
    for (const c of usable) {
      if (!inside(c.pos)) { outside++; continue; }
      const line = key(c);
      if (!own.includes(line)) own.push(line);
    }
    if (!own.length) continue;
    table[part] = own.join(';');
    parts++;
    kept += own.length;
    if (i % 1000 === 0) console.log(`::progress ${i + 1}/${files.length}`);
  }

  const body = Object.keys(table).sort().map((p) => `  '${p}': '${table[p]}',`).join('\n');
  writeFileSync(OUT,
    `// Generated by scripts/import-studio-connectivity.ts from BrickLink Studio's ldraw/connectivity.\n` +
    `// One connection per entry: 'M' a stud or 'F' an anti-stud, the part-space point, and the axis\n` +
    `// the mating stud runs along (LDraw: a top socket opens at +Y, a top stud points at -Y).\n` +
    `// Studio's grid repeats are not written out: the editor derives its own per-cell grids from the\n` +
    `// geometry, so only the first cell of each record is kept, and studioSnapsFor() skips a record\n` +
    `// whose first cell the model already has.\n` +
    `export const STUDIO_CONNECTORS: Readonly<Record<string, string>> = {\n${body}\n};\n`);
  console.log(`${files.length} files -> ${parts} parts, ${kept} connections (${noModel} parts not in public/ldraw)`);
  console.log(`skipped: ${unclear} files whose tail shapes are not all identified; ${ambiguous} parts with a pin, bar or joint`);
  console.log(`dropped: ${outside} outside their part's body by more than ${MARGIN} LDU, ${left} records of unverified codes`);
  console.log(`wrote ${OUT}`);
}

void main();
