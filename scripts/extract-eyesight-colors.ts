/**
 * Reads BrickLink Studio's own brick colours (the base colour of every material in
 * PhotoRealisticRenderer/mac/settings_v1.xml) into src/data/eyesightColors.generated.ts,
 * so the viewport can show the colours EyeSight renders instead of LDraw's approximations.
 *
 *   npx tsx scripts/extract-eyesight-colors.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const settings = join('/Applications/Studio 2.0/PhotoRealisticRenderer/mac', 'settings_v1.xml');
const xml = readFileSync(settings, 'utf8');
const table: Record<string, [number, number, number]> = {};
for (const m of xml.matchAll(/<material [^>]*?name="([A-Z]+-[A-Z0-9_-]+)"[^>]*>([\s\S]*?)<\/material>/g)) {
  const color = /<color name="[^"]*" value="([^"]+)"/.exec(m[2]);
  if (!color) continue;
  const rgb = color[1].trim().split(/\s+/).map(Number);
  if (rgb.length >= 3 && rgb.slice(0, 3).every(Number.isFinite)) table[m[1]] = [rgb[0], rgb[1], rgb[2]].map((v) => +v.toFixed(5)) as [number, number, number];
}
const body = Object.entries(table).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': [${v.join(', ')}],`).join('\n');
writeFileSync(join('src', 'data', 'eyesightColors.generated.ts'),
  `// Generated by scripts/extract-eyesight-colors.ts from BrickLink Studio's settings_v1.xml. Linear RGB.\nexport const EYESIGHT_COLORS: Readonly<Record<string, readonly [number, number, number]>> = {\n${body}\n};\n`);
console.log(`✓ ${Object.keys(table).length} colours`);
