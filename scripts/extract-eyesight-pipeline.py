"""Extract group-scoped EyeSight settings. No engine execution or inferred image grading.

python3 scripts/extract-eyesight-pipeline.py [installed-renderer-directory]
Writes src/data/eyesightPipeline.generated.ts; XML values do not establish runtime overrides.
"""
import hashlib
import json
from pathlib import Path
import argparse
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser()
parser.add_argument('source', nargs='?', default='/Applications/Studio 2.0/PhotoRealisticRenderer/mac')
parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/data/eyesightPipeline.generated.ts')
args = parser.parse_args()
source = Path(args.source)
settings = source / 'settings_v1.xml'
xml = settings.read_bytes()
root = ET.fromstring(xml)
solid = root.find("group[@name='SOLID-GROUP']/shader")
uv = root.find("group[@name='UVGroup']/shader")
assert solid is not None and uv is not None

def number_input(node, name):
    element = node.find(f"input[@name='{name}']")
    if element is None or 'value' not in element.attrib:
        raise ValueError(f'Missing scalar input {name}')
    return float(element.attrib['value'])

principled = solid.find('principled_bsdf')
roughness_link = solid.find("connect[@to_socket='Roughness']")
if roughness_link is None or roughness_link.attrib['from_socket'] != 'OutRoughness':
    raise ValueError('SOLID-GROUP roughness graph changed; inspect the new connection')
if uv.find("uv_degradation/input[@name='enable']").attrib['value'] != 'False':
    raise ValueError('UV degradation is enabled; static roughness bypass is no longer valid')
roughness = float(solid.find("value[@name='MinRoughness']").attrib['value'])
lights = ET.parse(source / 'settings_camera_light.xml').getroot()
rig = []
for transform in lights.find("preset[@name='BUILD_FL']").findall('transform'):
    light = transform.find('light')
    matrix = [float(v) for v in transform.attrib['matrix'].split()]
    rig.append({'name': light.attrib['name'], 'type': light.attrib['type'],
                'size': float(light.attrib['size']),
                'strength': number_input(light.find('shader/emission'), 'Strength'),
                'sourceZ': [matrix[2], matrix[6], matrix[10]]})
film = root.find('film')
background = ET.parse(source / 'LEGO_StudioSet.xml').getroot().find('background/shader/background_shader')
result = {
    'settingsSHA256': hashlib.sha256(xml).hexdigest(),
    'solid': {'roughness': roughness, 'ior': number_input(principled, 'IOR'),
              'specular': number_input(principled, 'Specular'),
              'clearcoat': number_input(principled, 'Clearcoat'),
              'clearcoatRoughness': number_input(principled, 'ClearcoatRoughness'),
              'uvDegradationEnabled': False},
    'film': {'exposure': float(film.attrib['exposure']), 'filter': film.attrib['filter_type'],
             'filterWidth': float(film.attrib['filter_width']), 'layer': film.find('layer').attrib},
    'worldStrength': number_input(background, 'Strength'),
    'buildFL': rig,
    'postprocessGraphsInSettingsXML': len(root.findall('postprocess')),
    'limitations': ['Static settings only; reference-render CLI overrides must be checked separately.',
                    'Denoising AO parameters do not establish an AO colour-multiplication operation.',
                    'Source coat weight is not numerically equivalent to glTF coat weight.',
                    'Distant-light size-to-angle conversion is not established by these XML files.'],
}
output = args.output
output.write_text('// Generated by scripts/extract-eyesight-pipeline.py from installed EyeSight XML.\n'
                  'export const EYESIGHT_PIPELINE = ' + json.dumps(result, indent=2) + ' as const;\n')
print(f'Extracted SOLID-GROUP roughness {roughness}; film {result["film"]["filter"]} {result["film"]["filterWidth"]}')
