import type { Mat3, Vec3 } from '../ldraw/parse';
import type { SceneSetup } from '../render/sceneSetup';

export type Rot = 0 | 90 | 180 | 270;
/** x, z in studs; y in plates (up is positive). Min corner of the rotated footprint, bottom of the piece. */
export type Grid = { x: number; y: number; z: number; rot: Rot };
/** Exact LDraw placement for imported pieces that are off the grid. */
export type Raw = { ldu: Vec3; matrix: Mat3 };

export type AssemblyRole = 'base' | 'hips' | 'leg' | 'torso' | 'arm' | 'hand' | 'head' | 'headwear' | 'neckwear' | 'generic';
/** Floor position in studs (x, z) and facing in degrees about the vertical axis. */
export type AssemblySpot = { x: number; z: number; angle: number };
/** References are sibling item IDs within the containing model, never part IDs. */
export type AssemblyHints = {
  attachTo?: string;
  after?: string[];
  /** Outward direction from the seated pose, in the containing model's frame. */
  insertionAxis?: Vec3;
  role?: AssemblyRole;
  /** Explicitly allow an independent/standalone foundation. */
  root?: boolean;
  /**
   * Moves where the piece waits on the floor before it flies in, in studs along
   * x and z, from the spot the automatic layout gives it. Set by dragging it.
   */
  floorShift?: [number, number];
  /** Editorial selection group, scoped to one model; independent of the build hierarchy. */
  group?: string;
  /** Build spot for a submodel use (absolute in main model's unmoved frame). */
  buildSpot?: AssemblySpot;
};

export type PieceItem = { assembly?: AssemblyHints; id?: string; part: string; color: string | number } & (Grid | Raw);
export type SubItem = { assembly?: AssemblyHints; id?: string; submodel: string } & (Grid | Raw);
export type PlanItem = PieceItem | SubItem;
/** A step's editorial metadata is optional, keeping older saved projects compatible. */
export type Step = {
  pieces: PlanItem[];
  title?: string;
  notes?: string;
  /** Extra seconds to hold on the completed step before the next action. */
  pauseAfter?: number;
  /** made by auto-steps (layers of a step-less file), not by the author: no editorial order inside it */
  auto?: boolean;
};
export type Submodel = { steps: Step[] };

/** Frames are integer and animation is non-destructive: keyed offsets never alter LDraw placements. */
export type AnimationChannel =
  | 'location.x' | 'location.y' | 'location.z'
  | 'rotation.x' | 'rotation.y' | 'rotation.z'
  | 'scale.x' | 'scale.y' | 'scale.z'
  | 'visibility';
export type KeyInterpolation = 'bezier' | 'linear' | 'constant';
export type AnimationKey = { frame: number; value: number; interpolation: KeyInterpolation };
/** One object action per authored item. `model` scopes the ID to its original hierarchy. */
export type ObjectAnimationTrack = {
  kind: 'object'; model: string; target: string;
  /** A baked leaf instance owns its own motion and visibility instead of sampling its live Build route. */
  source?: 'baked-flight';
  channels: Partial<Record<AnimationChannel, AnimationKey[]>>;
};
/** Live, non-destructive construction layer under manually keyed object offsets.
 * Stored per editable model; the underlying build remains generated by its planner. */
export type BuildAnimationLayer = { startFrame: number; speed: number };
/** A separate animation document; later bone/rig tracks can be added alongside objects. */
export type KeyframeAnimation = {
  fps: number; startFrame: number; endFrame: number;
  tracks: ObjectAnimationTrack[];
  /** Optional procedural Build layer for each model, updated when Build is replanned. */
  buildLayers?: Record<string, BuildAnimationLayer>;
};

export type Plan = {
  format: 'brickmotion-plan';
  version: 1;
  name: string;
  description?: string;
  submodels?: Record<string, Submodel>;
  /** custom part definitions embedded in imported files: file name (e.g. "custom.dat") → LDraw text */
  parts?: Record<string, string>;
  steps: Step[];
  /** Independent Dope Sheet animation; ignored by construction and LDraw export. */
  animation?: KeyframeAnimation;
  /** Project-local cameras, lamps, and render border. */
  sceneSetup?: SceneSetup;
  assemblySpot?: AssemblySpot;
  /**
   * Overrides for planner-generated work bays (Construction V2/V3 anatomical
   * and mechanical subassemblies), keyed by the exact planned group ID.
   * Group IDs include their nesting path, so duplicate submodel uses never
   * share an entry. IDs are scoped to the model being planned, so editing a
   * submodel alone and the full set keep independent bay placements.
   * Missing entries use the automatic bay.
   */
  workBaySpots?: Record<string, AssemblySpot>;
  /** default true: loose pieces move and turn with the main spot */
  loosePiecesFollow?: boolean;
  /** Preview the main model and each placed submodel at its own build spot in the Build editor. */
  showModelAtSpot?: boolean;
  /**
   * Assembly plan artifact (BrickMotion assembly plan v1, cold JSON) planned by
   * the Python engine for this exact model. Shapes and validity are checked by
   * the `assembly-artifact` planner; stored as an opaque value so projects keep
   * working even when the artifact could not be parsed.
   */
  assemblyPlan?: unknown;
};

export const isSub = (i: PlanItem): i is SubItem => 'submodel' in i;
export const isGrid = <T extends PlanItem>(i: T): i is T & Grid => 'rot' in i;

export function emptyPlan(name = 'Untitled set'): Plan {
  return { format: 'brickmotion-plan', version: 1, name, steps: [] };
}
