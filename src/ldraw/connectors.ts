import type { Box } from './flatten';
import type { Vec3 } from './parse';

/** Ordinary top studs only. Under-tubes and recessed underside primitives are NOT studs. */
export type StudConnector = { base: Vec3; tip: Vec3; radius: number };
/** A potential underside seat, not a collision exemption or a CAD socket certificate. */
export type SocketFace = { origin: Vec3; u: Vec3; v: Vec3 };
export type ConnectionGeometry = { studs?: StudConnector[]; socketFace?: SocketFace };

const dot = (a: readonly number[], b: readonly number[]) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const sub = (a: readonly number[], b: readonly number[]): Vec3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const point = (e: readonly number[], p: Vec3): Vec3 => [
  e[0] * p[0] + e[4] * p[1] + e[8] * p[2] + e[12],
  e[1] * p[0] + e[5] * p[1] + e[9] * p[2] + e[13],
  e[2] * p[0] + e[6] * p[1] + e[10] * p[2] + e[14],
];
const vector = (e: readonly number[], p: Vec3): Vec3 => [
  e[0] * p[0] + e[4] * p[1] + e[8] * p[2],
  e[1] * p[0] + e[5] * p[1] + e[9] * p[2],
  e[2] * p[0] + e[6] * p[1] + e[10] * p[2],
];

export function bottomSocketFace(body: Box, description: string): SocketFace | undefined {
  // These faces guide ORDER only. Actual geometry must still permit the flight.
  // Do not infer a rectangular socket on heads, caps, wheels or custom geometry.
  if (!/^(?:[=_~]+\s*)?(?:brick|plate|tile|slope|wedge)\b/i.test(description)) return undefined;
  const w = body.max[0] - body.min[0], d = body.max[2] - body.min[2];
  if (w < 12 || d < 12) return undefined;
  return { origin: [body.min[0], body.max[1], body.min[2]], u: [w, 0, 0], v: [0, 0, d] };
}

/** Known recessed underside: the bogie axle boxes extend below its mounting deck.
 * This is ordering metadata only, never a collision exemption. It also upgrades
 * model-only reproductions recorded before this connector profile existed.
 */
export function connectionGeometryFor(part: string, geometry: ConnectionGeometry & { body: Box }): ConnectionGeometry {
  const id = part.toLowerCase().replace(/\.dat$/, '').split('/').pop();
  if (id === '2878' && !geometry.socketFace &&
      Math.abs(geometry.body.min[0] + 60) < 0.1 && Math.abs(geometry.body.max[0] - 60) < 0.1 &&
      Math.abs(geometry.body.min[2] + 30) < 0.1 && Math.abs(geometry.body.max[2] - 30) < 0.1)
    return { ...geometry, socketFace: { origin: [-60, 24, -30], u: [120, 0, 0], v: [0, 0, 60] } };
  // Standard minifigure legs have a one-stud socket in the sole of each foot.
  // Treat the sole as connector metadata only; collision permission remains
  // limited to the fitted stud cylinder generated by discoverConnections().
  // This also upgrades model-only reproductions recorded before foot sockets
  // were captured by the metrics pipeline.
  if ((id === '3816' || id === '3817') && !geometry.socketFace) {
    const b = geometry.body, w = b.max[0] - b.min[0], d = b.max[2] - b.min[2];
    if (Math.abs(w - 18) < .5 && Math.abs(d - 20) < .5 && Math.abs(b.max[1] - 28) < .5)
      return { ...geometry, socketFace: { origin: [b.min[0], b.max[1], b.min[2]], u: [w, 0, 0], v: [0, 0, d] } };
  }
  // Classic mug/cup 3899 has a one-stud anti-stud in its underside.  The
  // flattened metrics used by older reproductions do not record that socket,
  // so recover only the known 20 x 20 bottom seat.  This metadata discovers a
  // stud connection; collision permission is still limited to the fitted stud
  // cylinders generated by the construction graph.
  if (id === '3899' && !geometry.socketFace) {
    const b = geometry.body, w = b.max[0] - b.min[0];
    if (Math.abs(w - 20) < .5 && Math.abs(b.max[1] - 18) < .5)
      return { ...geometry, socketFace: { origin: [-10, 24, -10], u: [20, 0, 0], v: [0, 0, 20] } };
  }
  return geometry;
}

/** Transform metadata in exactly the same frame as the graph's part boxes. */
export function transformConnections(g: ConnectionGeometry, e: readonly number[]): ConnectionGeometry {
  const radiusScale = Math.max(Math.hypot(e[0], e[1], e[2]), Math.hypot(e[8], e[9], e[10]));
  const face = g.socketFace;
  // u cross v points into the part. Reflections reverse that normal, so swap
  // the face axes without changing its covered footprint.
  const determinant = e[0] * (e[5] * e[10] - e[9] * e[6]) - e[4] * (e[1] * e[10] - e[9] * e[2]) + e[8] * (e[1] * e[6] - e[5] * e[2]);
  return {
    studs: g.studs?.map((s) => ({ base: point(e, s.base), tip: point(e, s.tip), radius: s.radius * radiusScale })),
    socketFace: face ? { origin: point(e, face.origin), u: vector(e, determinant < 0 ? face.v : face.u), v: vector(e, determinant < 0 ? face.u : face.v) } : undefined,
  };
}

/**
 * A stud's BASE, not the parent's outer AABB top, meets the receiving underside.
 * Recessed studs (e.g. 6157), side studs and reflected imports then order correctly.
 * This establishes a potential attachment/dependency; it NEVER bypasses collision tests.
 */
export function studFitsFace(stud: StudConnector, face: SocketFace, tolerance = 0.5): boolean {
  const { u, v } = face;
  const normal: Vec3 = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  const length = Math.hypot(...normal);
  const axis = sub(stud.tip, stud.base), height = Math.hypot(...axis);
  if (!Number.isFinite(length + height + stud.radius) || length < 1e-8 || height < 1e-8 || stud.radius <= 0) return false;
  for (let k = 0; k < 3; k++) normal[k] /= length;
  // Pointing into the socket, not away from it or across it.
  if (dot(normal, axis) / height < 0.995) return false;
  const r = sub(stud.base, face.origin);
  if (Math.abs(dot(normal, r)) > tolerance) return false;
  const uu = dot(u, u), uv = dot(u, v), vv = dot(v, v), det = uu * vv - uv * uv;
  if (det < 1e-10) return false;
  const ru = dot(r, u), rv = dot(r, v);
  const a = (ru * vv - rv * uv) / det, b = (rv * uu - ru * uv) / det;
  // Keep the whole stud inside the footprint, even for a skewed parallelogram.
  const ma = Math.max(0, stud.radius - tolerance) * Math.sqrt(vv / det);
  const mb = Math.max(0, stud.radius - tolerance) * Math.sqrt(uu / det);
  return a >= ma && a <= 1 - ma && b >= mb && b <= 1 - mb;
}
