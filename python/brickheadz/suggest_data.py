"""Mine "what goes where" from real LDraw models, for the editor's next-piece suggestions.

For every exact connection in every model (brickheadz.connectors), record where the other
piece sits in the frame of the first: the relative transform rel = inv(W_anchor) @ W_other.
The same relation seen again on the same anchor part is a habit builders have, so the editor
can put a ghost there and check it with its own connectors and collision test.

Also counts which part comes next in file order (the order builders place pieces in).

Usage:
  python -m brickheadz.suggest_data OUT.ts MODEL_FILES_OR_DIRS...
"""
from __future__ import annotations

import collections
import glob
import hashlib
import json
import os
import sys
from datetime import date

import numpy as np

from brickheadz import connectors as cg
from brickheadz.dat import load_pieces
from brickheadz.knowledge import canonical

ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "public", "ldraw")
TOP_REL = 16  # relations kept per anchor part
TOP_NEXT = 10


def model_files(paths: list[str]) -> list[str]:
    out = []
    for p in paths:
        if os.path.isdir(p):
            for ext in ("mpd", "ldr"):
                out += glob.glob(os.path.join(p, "**", f"*.{ext}"), recursive=True)
        elif os.path.isfile(p):
            out.append(p)
    return sorted(set(out))


def rel_key(m: np.ndarray) -> tuple:
    """Relative transform rounded: rotation to 3 decimals, translation to 1 LDU."""
    r = np.round(m[:3, :3], 3) + 0.0
    t = np.round(m[:3, 3]) + 0.0
    return tuple(r.flatten().tolist()) + tuple(t.tolist())


def mine(files: list[str]) -> dict:
    cat = cg.catalog()
    rel_models: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)  # anchor -> (other, key) -> models
    rel_same_colour: dict[tuple, int] = collections.Counter()
    nxt: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    seen_files, seen_models = set(), set()
    used = []
    for f in files:
        try:
            raw = open(f, "rb").read()
        except OSError:
            continue
        h = hashlib.sha256(raw).hexdigest()
        if h in seen_files:
            continue
        seen_files.add(h)
        try:
            ps = load_pieces(f)
        except Exception:
            continue
        if len(ps) < 4:
            continue
        parts = [canonical(ROOT, p.base_part) for p in ps]
        # the same model saved twice (steps edited, renamed): same pieces at the same places
        sig = hashlib.sha256(json.dumps(sorted(
            (pt, p.color, tuple(np.round(p.matrix[:3, 3]).tolist())) for pt, p in zip(parts, ps))).encode()).hexdigest()
        if sig in seen_models:
            continue
        seen_models.add(sig)
        try:
            g = cg.graph_of_pieces(ps, cat)
        except Exception as e:  # pragma: no cover
            print("skip", f, e, file=sys.stderr)
            continue
        used.append(os.path.basename(f))
        here: set = set()
        for e in g.edges:
            # Edge.rel is between the two connectors; the editor needs piece to piece
            rel = np.linalg.inv(ps[e.a].matrix) @ ps[e.b].matrix
            for anchor, other, m in ((e.a, e.b, rel), (e.b, e.a, np.linalg.inv(rel))):
                k = (parts[anchor], parts[other], rel_key(m))
                if k in here:
                    continue
                here.add(k)
                rel_models[parts[anchor]][(parts[other], k[2])] += 1
                if ps[anchor].color == ps[other].color:
                    rel_same_colour[k] += 1
        for i in range(len(ps) - 1):
            if ps[i].submodel == ps[i + 1].submodel:
                nxt[parts[i]][parts[i + 1]] += 1
    relations = {}
    for anchor, cnt in rel_models.items():
        rows = []
        for (other, key), n in cnt.most_common(TOP_REL):
            if n < 2:  # seen once is an accident, not a habit
                continue
            same = rel_same_colour[(anchor, other, key)] / n
            rows.append([other, n, round(same, 2), *[float(x) for x in key]])
        if rows:
            relations[anchor] = rows
    following = {p: [[q, n] for q, n in c.most_common(TOP_NEXT) if n >= 2] for p, c in nxt.items()}
    following = {p: v for p, v in following.items() if v}
    return {"models": used, "relations": relations, "next": following}


def write_ts(data: dict, out: str) -> None:
    n_rel = sum(len(v) for v in data["relations"].values())
    head = (f"// GENERATED by python/brickheadz/suggest_data.py on {date.today().isoformat()}. Do not edit by hand.\n"
            f"// Mined from {len(data['models'])} LDraw models ({n_rel} relations on {len(data['relations'])} anchor parts).\n\n"
            "/** [other part, models seen in, share with the anchor's colour, r00..r22 (row-major), tx, ty, tz] —\n"
            " * where `other` sits in the anchor's frame (LDU, LDraw axes): W_other = W_anchor · rel. */\n"
            "export type Relation = [string, number, number, ...number[]];\n\n")
    body = (f"export const MODEL_COUNT = {len(data['models'])};\n\n"
            f"export const RELATIONS: Record<string, Relation[]> = {json.dumps(data['relations'], separators=(',', ':'))};\n\n"
            "/** Which part builders place right after this one (file order): [part, times]. */\n"
            f"export const NEXT_PART: Record<string, [string, number][]> = {json.dumps(data['next'], separators=(',', ':'))};\n")
    open(out, "w").write(head + body)


if __name__ == "__main__":
    out, *paths = sys.argv[1:]
    d = mine(model_files(paths))
    write_ts(d, out)
    print(f"{len(d['models'])} models, {len(d['relations'])} anchor parts, "
          f"{sum(len(v) for v in d['relations'].values())} relations -> {out}")
