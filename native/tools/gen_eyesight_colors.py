"""Writes native/render/src/prep/eyesight_colors.inc from src/data/eyesightColors.generated.ts
(BrickLink Studio's own linear colours, read from its settings_v1.xml by
scripts/extract-eyesight-colors.ts), so the native renderer draws the colours EyeSight does.

    python3 native/tools/gen_eyesight_colors.py
"""
import os, re
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(REPO, 'src', 'data', 'eyesightColors.generated.ts')).read()
rows = re.findall(r"'([A-Z0-9_-]+)': \[([^\]]+)\]", src)
with open(os.path.join(REPO, 'native', 'render', 'src', 'prep', 'eyesight_colors.inc'), 'w') as f:
    f.write('// Generated by native/tools/gen_eyesight_colors.py from src/data/eyesightColors.generated.ts. Linear RGB.\n')
    for name, rgb in rows:
        r, g, b = [float(v) for v in rgb.split(',')]
        f.write('{"%s", {%.7ef, %.7ef, %.7ef}},\n' % (name, r, g, b))
print(len(rows), 'colours')
